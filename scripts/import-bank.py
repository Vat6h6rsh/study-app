def clean(value):
    value = re.sub(r'```[\s\S]*?```', '', value)
    value = re.sub(r'^\|.*$', '', value, flags=re.M)
    value = re.sub(r'\[([^\]]+)\]\([^)]+\)', r'\1', value)
    return re.sub(r'\n{3,}', '\n\n', value.replace('**', '').replace('`', '')).strip()

